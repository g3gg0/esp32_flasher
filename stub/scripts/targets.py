#!/usr/bin/env python3
"""Single target registry: per-chip target.json -> build settings/browser bounds."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def load_targets():
    targets = {}
    for path in sorted(ROOT.glob('esp32*/target.json')):
        config = json.loads(path.read_text())
        if config['cpu'] not in ('riscv32', 'xtensa'):
            raise ValueError(f'Unknown CPU: {path}')
        if int(config['text'], 0) % 16 or int(config['data'], 0) % 64:
            raise ValueError(f'Unaligned RAM: {path}')
        if config['dataBudget'] < config['stack'] + 1024:
            raise ValueError(f'Insufficient RAM: {path}')
        text,data=int(config['text'],0),int(config['data'],0)
        if text < data+config['dataBudget'] and data < text+config['textBudget']:
            raise ValueError(f'Overlapping code/data reservations: {path}')
        targets[path.parent.name] = config
    return targets


def browser_targets():
    return {name: {
        'textStart': int(cfg['text'], 0), 'textBudget': cfg['textBudget'],
        'dataStart': int(cfg['data'], 0), 'dataBudget': cfg['dataBudget'],
        'stackBytes': cfg['stack'], 'cpu': cfg['cpu'], 'cores': cfg['cores'],
        'transports': cfg['transports'], 'sdmmc': cfg.get('sdmmc', False)
    } for name, cfg in load_targets().items()}


def generate(check=False):
    target = ROOT / 'targets.js'
    content = ('// Generated by scripts/targets.py from esp32*/target.json.\n'
               '(function(root) {\n    const targets = ' + json.dumps(browser_targets(), indent=2) + ';\n'
               '    if (typeof module === "object" && module.exports) module.exports = targets;\n'
               '    else (root.ESPIO ||= {}).acceleratedTargets = targets;\n})(globalThis);\n')
    if check:
        if not target.exists() or target.read_text() != content:
            raise SystemExit('Stale generated targets.js; run python3 scripts/targets.py')
    elif not target.exists() or target.read_text() != content:
        target.write_text(content, newline='\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
