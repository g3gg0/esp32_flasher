#!/usr/bin/env python3
"""Generate read-only public eFuse profiles from the ESP-IDF 6.1 SDK tables."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import struct
import subprocess
import zlib

ROOT=Path(__file__).resolve().parents[1]
FIELDS=re.compile(r'^(WR_DIS|RD_DIS|MAC|OPTIONAL_UNIQUE_ID|WAFER_VERSION.*|CHIP_VER.*|PKG_VERSION|FLASH_CRYPT_CNT|SPI_BOOT_CRYPT_CNT|SECURE_BOOT_EN|ABS_DONE_[01]|SECURE_VERSION|SECURE_BOOT_KEY_REVOKE\d+|KEY_PURPOSE_\d+(?:_HI)?|JTAG_DISABLE|HARD_DIS_JTAG|SOFT_DIS_JTAG|DIS_(?:PAD_JTAG|USB_JTAG|USB_SERIAL_JTAG|DOWNLOAD.*)|DISABLE_DL_.*|ENABLE_SECURITY_DOWNLOAD|SECURE_DOWNLOAD_EN|UART_PRINT_CONTROL|UART_PRINT_CHANNEL|CONSOLE_DEBUG_DISABLE|FLASH_(?:TYPE|CAP|SIZE|VENDOR)|PSRAM_(?:CAP|SIZE|TYPE|VENDOR)|VDD_SPI_.*|XPD_SDIO_.*|SDIO_(?:TIEH|FORCE)|CODING_SCHEME|BLK_VERSION_.*)$')

def profile(idf,chip,revision):
    components=idf/'components';soc=components/'soc'/chip
    macros={}
    paths=[soc/'include/soc/soc.h',soc/'include/soc/reg_base.h',soc/'register/soc/reg_base.h',soc/'register/hw_ver1/soc/reg_base.h',soc/'register/soc/efuse_reg.h',soc/'register/hw_ver1/soc/efuse_reg.h']
    for path in paths:
        if path.exists():
            for name,expression in re.findall(r'^#define[ \t]+(\w+)[ \t]+([^\n]+)',path.read_text(encoding='utf-8'),re.M):macros[name]=expression.split('//')[0].strip()
    def evaluate(expression):
        if expression in macros:return evaluate(macros[expression])
        expression=re.sub(r'\b(0x[\da-fA-F]+|\d+)[uUlL]+\b',r'\1',expression)
        expression=re.sub(r'\b[A-Za-z_]\w*\b',lambda m:str(evaluate(macros[m[0]])),expression)
        if not re.fullmatch(r'[\d\s()+xabcdefABCDEF\-]+',expression):raise ValueError(expression)
        return eval(expression,{'__builtins__':{}},{})
    utility=(components/'efuse'/chip/'esp_efuse_utility.c').read_text(encoding='utf-8')
    ranges=re.findall(r'\{\s*(\w+)\s*,\s*(\w+)\s*\}',utility.split('range_read_addr_blocks[] = {')[1].split('};')[0])
    bases=[evaluate(a) for a,b in ranges];ends=[evaluate(b) for a,b in ranges]
    csv_path=components/'efuse'/chip/'esp_efuse_table.csv';text=csv_path.read_text(encoding='utf-8');all_fields={};name=None
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith('#'):continue
        parts=[s.strip() for s in line.split(',',4)]
        if len(parts)<5:continue
        key,block,start,count,description=parts
        if key:name=key;all_fields[name]={'name':name,'description':description,'segments':[]}
        if name and FIELDS.fullmatch(name) and re.fullmatch(r'EFUSE_BLK\d+',block):
            all_fields[name]['segments'].append([int(block[9:]),int(start),int(count)])
    fields=[];addresses=set()
    for name,f in all_fields.items():
        if not FIELDS.fullmatch(name) or not f['segments']:continue
        pieces=[]
        for block,start,count in f['segments']:
            while count:
                address=bases[block]+start//32*4;shift=start%32;bits=min(count,32-shift)
                if address>ends[block]:raise ValueError((chip,name,'outside shadow block'))
                pieces.append([address,shift,bits]);addresses.add(address);start+=bits;count-=bits
        f['pieces']=pieces;f['bits']=sum(n for b,s,n in f.pop('segments'))
        if not 1<=f['bits']<=256 or len(name.encode())>63:raise ValueError((chip,name,'record bounds'))
        f['description']=re.sub(r'^\[[^]]*\]\s*','',f['description']);fields.append(f)
    words=sorted(addresses)
    for f in fields:f['pieces']=[[words.index(a),s,n] for a,s,n in f['pieces']]
    version=components/'esp_rom'/chip/'ld'/f'{chip}.rom.version.ld'
    rom={k:int(v,16) for k,v in re.findall(r'(_rom_(?:chip_id|eco_version))\s*=\s*(0x[\da-f]+)',version.read_text() if version.exists() else '')}
    return {'chip':chip,'words':words,'schema':zlib.crc32(b''.join(struct.pack('<I',w) for w in words)),
            'fields':fields,'rom':{'chipAddress':rom.get('_rom_chip_id',0),'ecoAddress':rom.get('_rom_eco_version',0),'base':0x4fc00000 if chip=='esp32p4' else 0x40000000},
            'source':f'https://github.com/espressif/esp-idf/blob/{revision}/components/efuse/{chip}/esp_efuse_table.csv',
            'sourceSha256':hashlib.sha256(text.encode()).hexdigest()}

def generate(idf,check=False):
    revision=subprocess.check_output(['git','-C',str(idf),'rev-parse','HEAD'],text=True).strip()
    profiles={p.parent.name:profile(idf,p.parent.name,revision) for p in sorted(ROOT.glob('esp32*/target.json'))}
    header=['/* Generated by generate-fuses.py from ESP-IDF; public read-only fields. */','#pragma once','#include <stdint.h>',
            'typedef struct { uint8_t word,shift,bits; } fuse_piece_t;',
            'typedef struct { const char *name; uint16_t bits,first; uint8_t type,count; } fuse_field_t;']
    for i,(chip,p) in enumerate(profiles.items()):
        schema=zlib.crc32(json.dumps(p['fields'],sort_keys=True).encode())
        header += [f'#{"elif" if i else "if"} CONFIG_IDF_TARGET_{chip.upper()}',f'#define FUSE_SCHEMA_ID {schema}u',f'#define FUSE_ROM_CHIP_ADDRESS {p["rom"]["chipAddress"]}u',f'#define FUSE_ROM_ECO_ADDRESS {p["rom"]["ecoAddress"]}u',f'#define FUSE_ROM_BASE {p["rom"]["base"]}u',f'#define FUSE_SOURCE "{p["source"]}"','static const uint32_t fuse_words[] = {'+','.join(f'{w:#x}u' for w in p['words'])+'};']
        pieces=[];fields=[]
        for f in p['fields']:
            name=f['name']
            kind=6 if name=='MAC' else 9 if name=='OPTIONAL_UNIQUE_ID' else 5 if name in ('FLASH_CRYPT_CNT','SPI_BOOT_CRYPT_CNT','SOFT_DIS_JTAG') else 4 if name=='SECURE_VERSION' else 3 if f['bits']==1 else 2 if name in ('WR_DIS','RD_DIS') else 1
            fields.append('{"FUSE.'+name+'",'+','.join(str(n) for n in (f['bits'],len(pieces),kind,len(f['pieces'])))+'}')
            pieces.extend(f['pieces'])
        header += ['static const fuse_piece_t fuse_pieces[] = {'+','.join('{'+','.join(map(str,piece))+'}' for piece in pieces)+'};','static const fuse_field_t fuse_fields[] = {'+','.join(fields)+'};']
    header += ['#else','#error No generated fuse profile for target','#endif']
    path=ROOT/'include/fuse-profiles.h';content='\n'.join(header)+'\n'
    if check:
        if not path.exists() or path.read_text()!=content:raise SystemExit(f'Stale {path}')
    elif not path.exists() or path.read_text()!=content:path.write_text(content,newline='\n')
    print(', '.join(f'{c}: {len(p["fields"])} fields / {len(p["words"])} words' for c,p in profiles.items()))

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--idf',type=Path,default=Path(os.environ.get('IDF_PATH',str(ROOT.parents[1]/'esptool-legacy-flasher-stub/esp-idf'))));parser.add_argument('--check',action='store_true');args=parser.parse_args();generate(args.idf,args.check)
