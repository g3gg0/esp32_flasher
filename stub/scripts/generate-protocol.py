#!/usr/bin/env python3
"""Generate packed C wire structures and browser constants from protocol.json."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TYPES = {"u8": ("uint8_t", 1), "u16": ("uint16_t", 2), "u32": ("uint32_t", 4), "char": ("char", 1)}


def generate():
    spec = json.loads((ROOT / "protocol.json").read_text())
    lines = ["/* Generated by scripts/generate-protocol.py; edit protocol.json. */", "#pragma once", "#include <stdint.h>", "#include <stddef.h>"]
    for key, value in spec["version"].items():
        lines.append(f"#define RPC_PROTOCOL_{key.upper()} {value}u")
    lines += [f'#define RPC_MAX_PACKET_LENGTH {spec["maxPacketLength"]}u', f'#define RPC_MAX_REGISTER_DELAY_US {spec["maxRegisterDelayUs"]}u', f'#define RPC_BUILD_VERSION "{spec["buildVersion"]}"']
    for group in ("status", "operations", "identityFlags", "registerOperations", "capabilities", "sdmmcResponseTypes", "sdmmcErrors", "peripheralErrors", "captureOperations", "rmtOperations", "rmtEncodings"):
        for name, value in spec[group].items():
            lines.append(f'#define RPC_{group.upper()}_{name} {value}u')
    layouts = {"header": {"fields": spec["header"]}, **spec["packets"]}
    for name, packet in layouts.items():
        fields = [] if name == "header" else ["    rpc_header_t header;"]
        offset = 0 if name == "header" else 8
        offsets = {}
        for field in packet["fields"]:
            fname, kind, *count = field
            ctype, width = TYPES[kind]
            offsets[fname] = offset
            offset += width * (count[0] if count else 1)
            fields.append(f'    {ctype} {fname}' + (f'[{count[0]}]' if count else '') + ';')
        packet["offsets"], packet["size"] = offsets, offset
        lines += [f'typedef struct __attribute__((packed)) {{', *fields, f'}} rpc_{name}_t;', f'_Static_assert(sizeof(rpc_{name}_t) == {offset}, "{name} wire size");']
        if "magic" in packet:
            if len(packet["magic"].encode("ascii")) != 4:
                raise ValueError("Wire magics must be exactly four ASCII bytes")
            lines.append(f'#define RPC_MAGIC_{name.upper()} "{packet["magic"]}"')
    lines += ["#define RPC_MODULES(X) \\"]
    entries = list(spec["modules"].items())
    for i, (name, module) in enumerate(entries):
        lines.append(f'    X({name}, "{module["command"]}", "{module["response"]}")' + (' \\' if i + 1 < len(entries) else ''))
    browser = '// Generated from stub/protocol.json.\n(function(root) {\n    const protocol = ' + json.dumps(spec, indent=2) + ';\n    if (typeof module === "object" && module.exports) module.exports = protocol;\n    else (root.ESPIO ||= {}).rpcProtocol = protocol;\n})(globalThis);\n'
    return {ROOT / "include/protocol.h": '\n'.join(lines) + '\n', ROOT / "protocol.js": browser}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Stale generated protocol: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.exists() or path.read_text() != content:
                path.write_text(content, newline="\n")
